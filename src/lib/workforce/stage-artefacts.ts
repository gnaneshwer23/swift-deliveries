function fill(template: string, input: ExecuteStepInput, upstream: UpstreamArtefact[]): string {
  const answers = input.mission.clarificationAnswers;
  return template
    .replaceAll("{req}", input.mission.requestText.trim().slice(0, 200))
    .replaceAll("{users}", answers["users"]?.trim() || "Primary users named in the request")
    .replaceAll(
      "{constraints}",
      answers["constraints"]?.trim() ||
        "No explicit constraints supplied. Assumed: no production deploy, no live integrations, human approval for external actions.",
    )
    .replaceAll(
      "{evidence}",
      upstream.length
        ? upstream.map((u) => `- ${u.title} (${u.kind})`).join("\n")
        : "No upstream artefacts.",
    );
}

function simulatedMarkdown(input: ExecuteStepInput, upstream: UpstreamArtefact[]): string {
  const sections = input.task.requiredSections.map((name) => {
    const key = name
      .toLowerCase()
      .replace(/[^a-z0-9 ]+/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    const hint = SECTION_HINTS[key] ?? "To be completed by the operator.";
    return `## ${name}\n${fill(hint, input, upstream)}`;
  });
  return `# ${input.task.title}\n\n> Simulated draft — no model was called. Replace placeholders before relying on this artefact.\n\n${sections.join("\n\n")}\n`;
}

