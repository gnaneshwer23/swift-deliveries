/**
 * Lifecycle stage artefacts for `build` missions.
 *
 * - Model output (when configured) must pass the stage's handoff contract.
 * - Without a model, a deterministic simulated draft is produced and clearly
 *   labelled as such — never presented as researched or generated work.
 * - The verify stage is fully deterministic: it re-checks every upstream
 *   contract and runs static prototype checks (the "Automatically tested" basis).
 */
import {
  checkMarkdownContract,
  checkPrototypeHtml,
  extractHtmlDocument,
  markdownSections,
} from "./contracts";
import type { ExecuteStepInput, UpstreamArtefact } from "./executor";
import type { EvidenceItem, QualityLabel, WfArtefact } from "./types";

type ArtefactDraft = Omit<WfArtefact, "id" | "createdAt" | "updatedAt">;

export type StageOutcome = {
  passed: boolean;
  artefact: ArtefactDraft;
  detail?: string | undefined;
};

export const GENERATION_SOURCE_PREFIX = "generation:";

function generationEvidence(input: ExecuteStepInput): EvidenceItem {
  const g = input.generated;
  if (g?.mode === "model") {
    return {
      classification: "inferences",
      statement: `Generated by ${g.model ?? "a language model"} from the mission request and upstream artefacts. Claims are model inferences unless an item cites a source.`,
      source: `${GENERATION_SOURCE_PREFIX}model:${g.model ?? "unknown"}`,
    };
  }
  return {
    classification: "assumptions",
    statement: `Simulated draft — deterministic template, no model call${g?.note ? ` (${g.note})` : ""}. Structure is real; content is placeholder for operator completion.`,
    source: `${GENERATION_SOURCE_PREFIX}simulated`,
  };
}

