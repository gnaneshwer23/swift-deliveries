const KIND_TITLES: Partial<Record<WfArtefact["kind"], string>> = {
  mission_charter: "Mission charter",
  research_dossier: "Research dossier",
  tech_radar: "Technology radar",
  prd: "Product requirements document",
  design_spec: "UX & UI specification",
  architecture: "Architecture & delivery plan",
  prototype_html: "Sandboxed working prototype (HTML)",
  test_report: "Automated verification report",
  release_pack: "Release candidate pack",
  evolution_plan: "Measurement & evolution plan",
};

function draft(
  input: ExecuteStepInput,
  kind: WfArtefact["kind"],
  content: string,
  format: WfArtefact["contentFormat"],
  labels: QualityLabel[],
  evidence: EvidenceItem[],
): ArtefactDraft {
  const base = KIND_TITLES[kind] ?? input.task.title;
  return {
    missionId: input.mission.id,
    workspaceId: input.mission.workspaceId,
    taskId: input.task.id,
    kind,
    title: kind === "research_dossier" ? `${base} — ${input.task.title}` : base,
    content,
    contentFormat: format,
    qualityLabels: labels,
    evidenceItems: evidence,
  };
}

function verificationReport(input: ExecuteStepInput, upstream: UpstreamArtefact[]): StageOutcome {
  const rows: Array<{ check: string; passed: boolean; detail: string }> = [];
  for (const u of upstream) {
    if (u.contentFormat === "html") {
      for (const c of checkPrototypeHtml(u.content)) {
        rows.push({
          check: `${u.title}: ${c.label}`,
          passed: c.passed,
          detail: c.passed ? "pass" : "fail",
        });
      }
    } else if (u.requiredSections.length) {
      const r = checkMarkdownContract(u.content, u.requiredSections);
      rows.push({
        check: `${u.title}: handoff contract`,
        passed: r.ok,
        detail: r.ok
          ? `${u.requiredSections.length} sections present`
          : [
              r.missing.length ? `missing: ${r.missing.join(", ")}` : "",
              r.empty.length ? `empty: ${r.empty.join(", ")}` : "",
            ]
              .filter(Boolean)
              .join("; "),
      });
    }
  }
  const hasPrototype = upstream.some((u) => u.contentFormat === "html");
  rows.push({
    check: "Prototype artefact exists",
    passed: hasPrototype,
    detail: hasPrototype ? "pass" : "missing",
  });

  const prd = upstream.find((u) => u.kind === "prd");
  const criteria = prd
    ? (markdownSections(prd.content).get("acceptance criteria") ?? "")
        .split("\n")
        .map((l) => l.replace(/^\s*(?:[-*]|\d+\.)\s*/, "").trim())
        .filter((l) => l.length > 3)
    : [];

  const failed = rows.filter((r) => !r.passed);
  const content = `# Automated verification report

## Result
${failed.length === 0 ? "**PASS** — all automated checks passed." : `**FAIL** — ${failed.length} of ${rows.length} checks failed. Release is blocked until resolved.`}

## Checks
| Check | Result | Detail |
| --- | --- | --- |
${rows.map((r) => `| ${r.check.replaceAll("|", "/")} | ${r.passed ? "✅ pass" : "❌ fail"} | ${r.detail.replaceAll("|", "/")} |`).join("\n")}

## Requirements traceability
${
  criteria.length
    ? `| PRD acceptance criterion | Automated coverage |\n| --- | --- |\n${criteria.map((c) => `| ${c.replaceAll("|", "/")} | Requires human review against the prototype |`).join("\n")}`
    : "No PRD acceptance criteria found to trace."
}

## Scope of this report
Static, reproducible checks only. Behavioural correctness, usability and domain safety still require human review — this report never implies them.
`;
  const evidence: EvidenceItem[] = [
    {
      classification: "sourced_facts",
      statement: `${rows.length - failed.length}/${rows.length} deterministic checks passed against stored artefacts.`,
      source: "executor.verify",
    },
    {
      classification: "assumptions",
      statement:
        "Static checks do not establish behavioural correctness or clinical/regulatory safety.",
    },
  ];
  return {
    passed: failed.length === 0,
    artefact: draft(
      input,
      "test_report",
      content,
      "markdown",
      failed.length ? [] : ["automatically_tested"],
      evidence,
    ),
    detail: failed.length ? `${failed.length} verification check(s) failed` : undefined,
  };
}

export function stageArtefact(input: ExecuteStepInput): StageOutcome {
  const kind = input.task.produces!;
  const upstream = input.upstream ?? [];
  const genEvidence = generationEvidence(input);
  const modelText = input.generated?.mode === "model" ? input.generated.content : null;

  if (kind === "test_report") return verificationReport(input, upstream);

  if (kind === "prototype_html") {
    const html = modelText ? extractHtmlDocument(modelText) : simulatedPrototype(input);
    if (!html) {
      return {
        passed: false,
        artefact: draft(input, kind, modelText ?? "", "markdown", [], [genEvidence]),
        detail: "Model output did not contain a complete HTML document.",
      };
    }
    const checks = checkPrototypeHtml(html);
    const sandboxSafe = checks.filter((c) => c.id.startsWith("no_")).every((c) => c.passed);
    return {
      passed: sandboxSafe,
      artefact: draft(input, kind, html, "html", sandboxSafe ? ["agent_reviewed"] : [], [
        genEvidence,
      ]),
      detail: sandboxSafe
        ? undefined
        : "Prototype loads remote scripts or makes network calls; rejected.",
    };
  }

  const content = modelText ?? simulatedMarkdown(input, upstream);
  const contract = checkMarkdownContract(content, input.task.requiredSections);
  const evidence: EvidenceItem[] = [
    genEvidence,
    {
      classification: contract.ok ? "sourced_facts" : "assumptions",
      statement: contract.ok
        ? `Handoff contract passed: ${input.task.requiredSections.length} required sections present.`
        : `Handoff contract failed — missing: ${contract.missing.join(", ") || "none"}; empty: ${contract.empty.join(", ") || "none"}.`,
      source: "contracts.checkMarkdownContract",
    },
  ];
  return {
    passed: contract.ok,
    artefact: draft(
      input,
      kind,
      content,
      "markdown",
      contract.ok ? ["agent_reviewed"] : [],
      evidence,
    ),
    detail: contract.ok ? undefined : `Contract failed (missing: ${contract.missing.join(", ")})`,
  };
}
